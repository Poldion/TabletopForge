/** Entfernt deutsche Adjektiv-Endungen: „roter“ → „rot“, „junge“ → „jung“. */
function stem(word) {
  for (const end of ['eren', 'erer', 'ere', 'em', 'en', 'er', 'es', 'e']) {
    const root = word.slice(0, -end.length);
    if (word.endsWith(end) && (WORDS[root] || TERMS[root])) return root;
  }
  return word;
}

/** Übersetzt einen (evtl. deutschen) Suchbegriff in einen englischen Namensteil. */
export function toEnglishQuery(q) {
  const s = q.trim().toLowerCase();
  if (!s) return '';
  if (DE_TO_EN[s]) return DE_TO_EN[s];
  const words = s.split(/\s+/);
  if (words.length > 1) {
    // Wort für Wort übersetzen, unbekannte Wörter bleiben stehen
    const out = words.map((w) => {
      const r = stem(w);
      return WORDS[r] || TERMS[r] || (DE_TO_EN[r] ? DE_TO_EN[r].toLowerCase() : w);
    });
    return out.join(' ');
  }
  // Teiltreffer im deutschen Namen, z.B. „eulen“ → Owlbear
  const partial = Object.entries(DE_TO_EN).find(([de]) => de.startsWith(s) && s.length >= 4);
  if (partial) return partial[1];
  for (const [de, en] of Object.entries(TERMS)) if (s.includes(de)) return en;
  return q.trim();
}

